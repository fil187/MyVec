#include <assert.h>
#include <iostream>
#include "my_vector.hpp"

void test_constructor() {
    MyVector<int> vector1;
    MyVector<int> vector2(150);
    int array[3] = {1, 2, 3};
    MyVector<int> vector3(array, 3);
    MyVector<int> vector4(vector3);

    assert(vector1.length() == 0);
    assert(vector2.length() == 0);
    assert(vector3.length() == 3);
    assert(vector4.length() == 3);
}

void test_push() {
    MyVector<int> vector;
    for (int i = 0; i <= 100; i++)
        vector.push(i);
    for (int i = 0; i <= 100; i++)
        assert(vector[i] == i);
}

void test_pop() {
    MyVector<int> vector;
    for (int i = 0; i <= 200; i++) // 200 triggers resize
        vector.push(i);
    for (int i = 200; i >= 0; i--)
        assert(vector.pop() == i);
}

